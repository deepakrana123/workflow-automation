def test_invalid_dimension_rejected():
    """Test: Invalid embedding dimensions are rejected."""
    print("\n[8] Invalid embedding dimensions are rejected")
    
    db = _session()
    _seed_multi_tenant(db)
    
    wk = _create_workflow_knowledge(db, workspace_id=1)
    rule1 = _create_business_rule(db, wk.id, "Rule 1")
    
    # Manually inject wrong dimension to test validation
    model = load_embedding_model()
    
    # Create a mock embedding with wrong dimension
    from unittest.mock import patch
    
    original_encode = model.encode
    
    def wrong_dim_encode(text, **kwargs):
        result = original_encode(text, **kwargs)
        # Truncate to wrong dimension
        return result[:, :100]  # Wrong: only 100 dimensions instead of 384
    
    with patch.object(model, 'encode', side_effect=wrong_dim_encode):
        stats = backfill_business_rules(db, model, force=False)
        
        chk("Invalid dimension: stats.failed > 0", stats.failed > 0, f"failed={stats.failed}")
        
        # Verify rule was not updated
        from app.models.workflow_business_rule import WorkflowBusinessRule
        rule1_v = db.query(WorkflowBusinessRule).filter_by(id=rule1.id).first()
        chk("Invalid dimension: rule not modified", rule1_v.embedding is None)
    
    db.close()


def test_failed_records_can_be_retried():
    """Test: Failed records are not updated and can be retried."""
    print("\n[9] Failed records can be retried")
    
    db = _session()
    _seed_multi_tenant(db)
    
    wk = _create_workflow_knowledge(db, workspace_id=1)
    rule1 = _create_business_rule(db, wk.id, "Rule 1", rule="")  # Empty rule
    rule2 = _create_business_rule(db, wk.id, "Rule 2")
    
    model = load_embedding_model()
    
    # First backfill should skip empty rule
    stats1 = backfill_business_rules(db, model, force=False)
    chk("First backfill: skipped=1 (empty rule)", stats1.skipped >= 1)
    
    from app.models.workflow_business_rule import WorkflowBusinessRule
    rule1_v1 = db.query(WorkflowBusinessRule).filter_by(id=rule1.id).first()
    rule2_v1 = db.query(WorkflowBusinessRule).filter_by(id=rule2.id).first()
    
    chk("Empty rule: still None", rule1_v1.embedding is None)
    chk("Valid rule: has embedding", rule2_v1.embedding is not None)
    
    # Update rule1 with valid content
    rule1_v1.rule = "Updated Rule 1"
    db.commit()
    
    # Second backfill should now process rule1
    stats2 = backfill_business_rules(db, model, force=False)
    chk("Second backfill: updated=1", stats2.updated == 1)
    
    rule1_v2 = db.query(WorkflowBusinessRule).filter_by(id=rule1.id).first()
    chk("Updated rule: now has embedding", rule1_v2.embedding is not None)
    
    db.close()


