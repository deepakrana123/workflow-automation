def test_business_rule_embeddings_generated():
    """Test: WorkflowBusinessRule embeddings are generated."""
    print("\n[1] WorkflowBusinessRule embeddings are generated")
    
    db = _session()
    _seed_multi_tenant(db)
    
    # Create workflow knowledge and rules without embeddings
    wk = _create_workflow_knowledge(db, workspace_id=1)
    rule1 = _create_business_rule(db, wk.id, "Rule 1")
    rule2 = _create_business_rule(db, wk.id, "Rule 2")
    
    chk("Initial: rule embeddings are None", rule1.embedding is None and rule2.embedding is None)
    
    # Load model and backfill
    model = load_embedding_model()
    stats = backfill_business_rules(db, model, force=False)
    
    chk("Backfill stats: total=2", stats.total == 2)
    chk("Backfill stats: updated=2", stats.updated == 2)
    chk("Backfill stats: skipped=0", stats.skipped == 0)
    chk("Backfill stats: failed=0", stats.failed == 0)
    
    # Refresh from DB
    from app.models.workflow_business_rule import WorkflowBusinessRule
    rule1_refreshed = db.query(WorkflowBusinessRule).filter_by(id=rule1.id).first()
    rule2_refreshed = db.query(WorkflowBusinessRule).filter_by(id=rule2.id).first()
    
    chk("After backfill: rule1.embedding is not None", rule1_refreshed.embedding is not None)
    chk("After backfill: rule2.embedding is not None", rule2_refreshed.embedding is not None)
    chk("After backfill: embedding dimensions are 384", 
        len(rule1_refreshed.embedding) == 384 and len(rule2_refreshed.embedding) == 384)
    
    db.close()


