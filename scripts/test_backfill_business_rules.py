def test_idempotency_with_workspace_scope():
    """Test: Workspace-scoped backfill is idempotent."""
    print("\n[5] Workspace-scoped backfill is idempotent")
    
    db = _session()
    entities = _seed_multi_tenant(db)
    
    # Create rules in two workspaces
    wk_a1 = _create_workflow_knowledge(db, workspace_id=1, workflow_name="WK_A1")
    wk_a2 = _create_workflow_knowledge(db, workspace_id=2, workflow_name="WK_A2")
    
    rule_a1 = _create_business_rule(db, wk_a1.id, "Rule A1")
    rule_a2 = _create_business_rule(db, wk_a2.id, "Rule A2")
    
    model = load_embedding_model()
    
    # First backfill workspace 1
    stats1 = backfill_business_rules(db, model, force=False, workspace_id=1)
    chk("First backfill WS1: updated=1", stats1.updated == 1)
    
    # Second backfill workspace 1 (should skip)
    stats2 = backfill_business_rules(db, model, force=False, workspace_id=1)
    chk("Second backfill WS1: updated=0", stats2.updated == 0)
    chk("Second backfill WS1: skipped=1", stats2.skipped == 1)
    
    # First backfill workspace 2
    stats3 = backfill_business_rules(db, model, force=False, workspace_id=2)
    chk("First backfill WS2: updated=1", stats3.updated == 1)
    
    # Verify both have embeddings
    from app.models.workflow_business_rule import WorkflowBusinessRule
    rule_a1_v = db.query(WorkflowBusinessRule).filter_by(id=rule_a1.id).first()
    rule_a2_v = db.query(WorkflowBusinessRule).filter_by(id=rule_a2.id).first()
    
    chk("Workspace 1 rule: has embedding", rule_a1_v.embedding is not None)
    chk("Workspace 2 rule: has embedding", rule_a2_v.embedding is not None)
    
    db.close()


