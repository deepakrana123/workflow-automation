"""
app/execution/domain_actions/catalog_stubs.py

Stub handlers for all catalog ActionDefinition entries that don't yet have
a real Python implementation.

Each stub:
  - Simulates realistic latency   (5–120 ms, random)
  - Has a small random failure rate (~8%) so retry/DLQ logic can be tested
  - Returns the action name + entity_id in outputs so traces are readable
  - Follows the exact same signature as every other handler:
      fn(payload: dict, config: dict) -> dict

Generated from .json catalog — one function per missing action name.
"""

import random
import time

# Failure probability per action invocation (8 %)
_FAIL_RATE = 0.08
# Latency range in seconds
_LAT_MIN, _LAT_MAX = 0.005, 0.12


def _stub(action_name: str, payload: dict, config: dict) -> dict:
    """Shared stub body — simulates latency + occasional failure."""
    time.sleep(random.uniform(_LAT_MIN, _LAT_MAX))
    if random.random() < _FAIL_RATE:
        return {
            "success": False,
            "error": f"{action_name}_stub_simulated_failure",
            "action": action_name,
            "entity_id": payload.get("entity_id"),
        }
    return {
        "success": True,
        "action": action_name,
        "entity_id": payload.get("entity_id"),
        "status": "completed",
    }


